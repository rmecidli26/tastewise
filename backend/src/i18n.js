export const normalizeLang = l => (LANGS.includes(l) ? l : null);

/** t('az', 'err.INVALID_CODE', { left: 3 }) */
export function t(lang, key, vars = {}) {
  const s = M[lang]?.[key] ?? M.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}
export const has = (lang, key) => Boolean(M[lang]?.[key] ?? M.en[key]);

/** Language for a request: X-Lang header → ?lang= → tw_lang cookie → Accept-Language → az */
export function pickLang(req) {
  const fromAccept = String(req.headers?.['accept-language'] || '')
    .split(',').map(p => p.trim().slice(0, 2).toLowerCase()).find(l => LANGS.includes(l));
  return normalizeLang(String(req.headers?.['x-lang'] || '').toLowerCase())
    || normalizeLang(String(req.query?.lang || '').toLowerCase())
    || normalizeLang(req.cookies?.tw_lang)
    || fromAccept
    || DEFAULT_LANG;
}

export function langMiddleware(req, res, next) {
  req.lang = pickLang(req);
  res.set('Content-Language', req.lang);
  next();
}

/** Picks a translated value from a JSONB translations object, falling back to the English column. */
export const localized = (i18n, lang, field, fallback) => {
  const v = field ? i18n?.[lang]?.[field] : i18n?.[lang];
  return v || fallback;
};
